// ─────────────────────────────────────────────────────────────────────────────
// ROW GENERATION
// ─────────────────────────────────────────────────────────────────────────────

function deterministicNoise(state, species, unit, year, weapon) {
  // Deterministic tiny variation so data doesn't look perfectly linear
  const hash = [...`${state}${species}${unit}${year}${weapon}`]
    .reduce((acc, c) => acc + c.charCodeAt(0), 0)
  return ((hash % 11) - 5) * 0.18 // ±0.9% noise
}

function generateRows() {
  const rows = []

  for (const [state, speciesMap] of Object.entries(DATA)) {
    if (STATE_FILTER && state !== STATE_FILTER) continue

    for (const [rawSpecies, units] of Object.entries(speciesMap)) {
      const species = rawSpecies.replace('_', ' ')

      for (const [unit, odds2024, avgPts2024, minPts2024, apps2024, trend] of units) {
        // Generate rifle, archery, muzzleloader
        const weapons = [
          { type: 'rifle',       oddsMult: 1.00, appsMult: 1.00 },
          { type: 'archery',     oddsMult: 1.60, appsMult: 0.45 },
          { type: 'muzzleloader', oddsMult: 1.35, appsMult: 0.30 },
        ]

        for (const { type, oddsMult, appsMult } of weapons) {
          for (const year of YEARS) {
            const yearsBack = 2024 - year
            const noise = deterministicNoise(state, species, unit, year, type)

            // Odds: trend takes us back in time, + noise
            const rawOdds = odds2024 + yearsBack * trend + noise
            const draw_odds_percent = Math.max(0.5, Math.min(99, rawOdds * oddsMult))

            // Applications: slightly fewer applicants in earlier years
            const appGrowth = 1 - yearsBack * 0.025  // ~2.5% annual growth
            const total_applicants = Math.max(20, Math.round(apps2024 * appsMult * appGrowth))

            const successful_draws = Math.max(1, Math.round(total_applicants * draw_odds_percent / 100))

            // Points: as odds improve (going back in time), fewer points needed
            const ptsFactor = Math.max(0, 1 - yearsBack * 0.05)
            const avg_points_drawn = avgPts2024 > 0
              ? Math.max(0, +(avgPts2024 * ptsFactor + noise * 0.2).toFixed(1))
              : 0
            const min_points_drawn = minPts2024 > 0
              ? Math.max(0, Math.round(minPts2024 * ptsFactor))
              : 0

            rows.push({
              state,
              species,
              unit_number: unit,
              weapon_type: type,
              year,
              draw_odds_percent: +draw_odds_percent.toFixed(1),
              avg_points_drawn: +avg_points_drawn.toFixed(1),
              min_points_drawn,
              total_applicants,
              successful_draws,
            })
          }
        }
      }
    }
  }

  return rows
}

// ─────────────────────────────────────────────────────────────────────────────
// MAIN
// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  const rows = generateRows()
  console.log(`Generated ${rows.length.toLocaleString()} rows across ${YEARS.length} years (${YEARS[0]}–${YEARS[YEARS.length - 1]}).`)

  if (DRY_RUN) {
    const byState = {}
    rows.forEach(r => { byState[r.state] = (byState[r.state] || 0) + 1 })
    console.table(byState)
    return
  }

  const supabase = createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL,
    process.env.SUPABASE_SERVICE_ROLE_KEY
  )

  let inserted = 0
  for (let i = 0; i < rows.length; i += BATCH) {
    const batch = rows.slice(i, i + BATCH)
    const { error } = await supabase
      .from('draw_odds')
      .upsert(batch, { onConflict: 'state,species,unit_number,weapon_type,year', ignoreDuplicates: false })

    if (error) {
      console.error(`Batch ${i}–${i + BATCH} failed:`, error.message)
    } else {
      inserted += batch.length
      process.stdout.write(`  Inserted ${inserted.toLocaleString()} / ${rows.length.toLocaleString()}\r`)
    }
  }

  console.log(`\nDone. ${inserted.toLocaleString()} rows upserted into draw_odds.`)
}

main().catch(err => { console.error(err); process.exit(1) })
